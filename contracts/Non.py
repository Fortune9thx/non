"""
Non -- a bonded constitutional tribunal on GenLayer.

Non settles one contested question on-chain:

    Does this proposal's material claims meet a pinned constitution under
    independently fetched evidence?

Outcomes: APPROVE | REJECT | REVISE | INCONCLUSIVE.

GenLayer owns the contested part: whether the proposal complies with the
case-pinned constitution version, and whether its material claims survive
evidence that each validator fetches for itself over HTTPS. The leader
does not get to assert a verdict and have it believed -- every validator
re-fetches the evidence, re-runs the prompt, and canonicalizes its own
verdict through the same pure code in contracts/non_lib.py. The leader's
result is accepted only when the two independently derived verdicts agree
on decision, outcome, and the case's pinned rules version.

Money makes a false verdict expensive. The proposer bonds GEN to open a
case; a challenger may bond during the appeal window. A final adverse
outcome forfeits the losing side's bond. INCONCLUSIVE refunds every bond
exactly -- there is no fee, and no silent approval, when the tribunal
cannot tell.

Studio Dev / Studio Next only (chain id 61997). State may reset.

This single file is what the network actually receives -- sibling imports
are not supported by contract validation, so scripts/build_bundle.py
inlines contracts/non_lib.py between the marker lines below. Do not
hand-edit the generated bundle; edit contracts/non_lib.py or this file and
re-run the bundler.
"""

