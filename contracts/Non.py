    @gl.public.write
    def register_scope(self, scope_id: str, admin: str) -> str:
        """Claims a scope id and names its admin. Scope ids are first-come;
        a registered scope can never be re-registered by anyone else."""
        try:
            sid = validate_identifier(scope_id)
            admin_hex = Address(admin).as_hex
        except NonValidationError as exc:
            raise gl.vm.UserError(exc.code)
        except Exception:
            raise gl.vm.UserError(USER_ERRORS["BAD_SCOPE_ID"])

        if self.scopes.get(sid) is not None:
            raise gl.vm.UserError(USER_ERRORS["SCOPE_EXISTS"])

        self._save_scope(sid, {
            "scope_id": sid,
            "admin": admin_hex,
            "constitution": None,
            "created_at": _now_ts(),
        })
        ScopeRegistered(Address(admin_hex), sid).emit()
        return sid

    @gl.public.write
    def set_constitution(self, scope_id: str, version: str, rules_text: str,
                         rules_json: str) -> str:
        """Pins a new constitution version for a scope. Only the scope
        admin (or the contract owner, for bootstrap) may call this.

        Amendments are forward-only: every already-open case keeps the
        version it was opened under, so nobody can retroactively change the
        rules a live case is judged by.
        """
        sid = validate_identifier(scope_id) if isinstance(scope_id, str) else ""
        rec = self._load_scope(sid)
        sender = Address(_sender()).as_hex
        if sender != rec["admin"] and sender != self.owner:
            raise gl.vm.UserError(USER_ERRORS["NOT_SCOPE_ADMIN"])

        try:
            constitution = validate_constitution(version, rules_text, rules_json)
        except NonValidationError as exc:
            raise gl.vm.UserError(exc.code)

        constitution["set_at"] = _now_ts()
        rec["constitution"] = constitution
        self._save_scope(sid, rec)
        ConstitutionSet(sid, constitution["version"]).emit()
        return constitution["version"]

    # -----------------------------------------------------------------
    # open_case
    # -----------------------------------------------------------------

    @gl.public.write.payable
    def open_case(self, scope_id: str, subject_json: str, evidence_urls: str) -> str:
        """Opens a case against a scope's current constitution, freezing
        that version onto the case. Attached GEN is the review bond and
        must be at least min_review_bond.

        `evidence_urls` is a JSON array of HTTPS urls -- at least one, at
        most MAX_EVIDENCE_URLS, no private or loopback hosts.
        """
        sid = validate_identifier(scope_id) if isinstance(scope_id, str) else ""
        scope = self._load_scope(sid)
        constitution = scope.get("constitution")
        if not constitution:
            raise gl.vm.UserError(USER_ERRORS["CONSTITUTION_MISSING"])

        try:
            subject = validate_subject(subject_json)
            urls = validate_evidence_urls(evidence_urls)
            bond = validate_bond(gl.message.value, int(self.min_review_bond))
        except NonValidationError as exc:
            raise gl.vm.UserError(exc.code)

        counter = int(self.case_counter) + 1
        self.case_counter = u256(counter)
        case_id = make_case_id(counter)
        proposer = Address(_sender()).as_hex
        now_ts = _now_ts()

        rec = {
            "case_id": case_id,
            "scope_id": sid,
            "proposer": proposer,
            "subject": subject,
            "evidence_urls": urls,
            "rules_version": constitution["version"],
            "rules_text": constitution["rules_text"],
            "rules_json": constitution["rules_json"],
            "state": STATE_OPEN,
            "opened_at": now_ts,
            "decided_at": 0,
            "finalized_at": 0,
            "review_bond": str(bond),
            "challenger": "",
            "challenge_bond": "0",
            "challenge_note": "",
            "settler": "",
            "settle_bond": "0",
            "decision": "",
            "outcome": "",
            "scores": {},
            "reasoning": "",
            "weak_spots": "",
            "corrections": "",
            "improvements": "",
            "uncertainty": "",
            "evidence_report": [],
            "eval_rounds": 0,
            "settled": False,
        }
        self._save_case(case_id, rec)
        self._index(self.address_cases, proposer, case_id)
        self._index(self.scope_cases, sid, case_id)
        CaseOpened(case_id, Address(proposer), sid,
                   rules_version=constitution["version"]).emit()
        return case_id

    # -----------------------------------------------------------------
    # evaluate_case -- the single non-deterministic step
    # -----------------------------------------------------------------

    @gl.public.write
    def evaluate_case(self, case_id: str) -> str:
        """Runs the adjudication under the equivalence principle and writes
        the decision. Permissionless -- anyone may pay the gas to move a
        case forward; nobody can influence the result by doing so.

        Callable from OPEN (first evaluation) and from a challenged
        DECIDED case (re-evaluation with the challenger's added evidence).
        """
        rec = self._load_case(case_id)
        state = rec["state"]
        now_ts = _now_ts()

        if state == STATE_FINAL:
            raise gl.vm.UserError(USER_ERRORS["ALREADY_FINAL"])
        if state == STATE_DECIDED and not rec["challenger"]:
            raise gl.vm.UserError(USER_ERRORS["ALREADY_DECIDED"])
        if state == STATE_DECIDED and rec.get("eval_rounds", 0) >= 2:
            raise gl.vm.UserError(USER_ERRORS["ALREADY_DECIDED"])
        if state not in (STATE_OPEN, STATE_DECIDED):
            raise gl.vm.UserError(USER_ERRORS["NOT_OPEN"])

        rec["state"] = STATE_REVIEWING
        self._save_case(case_id, rec)

        # Plain local copies -- the ONLY values the nondet closures see.
        # Storage objects never cross into a nondeterministic block.
        urls = list(rec["evidence_urls"])
        subject = dict(rec["subject"])
        rules_version = rec["rules_version"]
        rules_text = rec["rules_text"]
        rules_json = rec["rules_json"]
        challenge_note = rec.get("challenge_note", "")

        def leader_fn() -> str:
            """Fetches every evidence url over HTTPS, normalizes each page
            into a record that carries its own limitations, and asks for a
            verdict. Runs identically on the leader and on every
            validator -- a validator never reads the leader's fetches."""
            records = []
            for url in urls:
                try:
                    page = gl.nondet.web.get(url)
                    body = getattr(page, "body", None)
                    if body is None:
                        body = str(page)
                    status = getattr(page, "status", 200)
                except Exception:
                    body = ""
                    status = 0
                records.append(normalize_evidence(url, status, body))

            evidence_ok = evidence_is_sufficient(records)
            if not evidence_ok:
                # Nothing was retrievable. Do not spend a prompt call to
                # reach a conclusion no evidence can support.
                verdict = canonicalize_verdict(
                    {"decision": DECISION_INCONCLUSIVE,
                     "outcome": "inconclusive",
                     "reasoning": "no evidence url could be retrieved"},
                    evidence_ok=False,
                )
            else:
                prompt = build_prompt(
                    rules_version=rules_version,
                    rules_text=rules_text,
                    rules_json=rules_json,
                    subject=subject,
                    evidence=records,
                    challenge_note=challenge_note,
                )
                try:
                    raw = gl.nondet.exec_prompt(prompt)
                except Exception:
                    raw = ""
                verdict = canonicalize_verdict(raw, evidence_ok=evidence_ok)

            verdict["rules_version"] = rules_version
            verdict["evidence"] = [{
                "url": r["url"],
                "status": r["status"],
                "ok": r["ok"],
                "title": r["title"],
                "limitations": r["limitations"],
            } for r in records]
            return json.dumps(verdict, sort_keys=True)

        def validator_fn(leader_result) -> bool:
            # The validator re-does the WHOLE job -- its own HTTPS fetches,
            # its own prompt, its own canonicalization -- and then compares
            # two independently derived verdicts. A leader that fabricated
            # a self-consistent envelope would pass a structural check; it
            # cannot pass this one unless the validator's own independent
            # work agrees on decision, outcome, and pinned rules version.
            # run_nondet hands the validator a `gl.vm.Return | gl.vm.VMError`,
            # NOT the leader's raw value -- the payload lives in .calldata.
            # str()-ing the wrapper yields a dataclass repr that never
            # parses as JSON, which would fail EVERY case closed.
            payload = getattr(leader_result, "calldata", None)
            if payload is None:
                return False  # VMError, or any shape without a return value
            try:
                leader_verdict = json.loads(str(payload))
            except (json.JSONDecodeError, TypeError):
                return False
            if not isinstance(leader_verdict, dict):
                return False

            mine = json.loads(leader_fn())
            return verdicts_equivalent(
                leader_verdict,
                mine,
                rules_version_match=(
                    leader_verdict.get("rules_version") == mine.get("rules_version")
                ),
            )

        raw_result = gl.vm.run_nondet(leader_fn, validator_fn)

        try:
            agreed = json.loads(str(raw_result))
        except (json.JSONDecodeError, TypeError):
            agreed = {}
        if not isinstance(agreed, dict):
            agreed = {}

        # Re-canonicalize the agreed result inside deterministic code. Even
        # a consensus-accepted envelope is re-run through the same pure
        # mapping before it is allowed to touch stored state.
        evidence_records = agreed.get("evidence", [])
        evidence_ok = any(bool(e.get("ok")) for e in evidence_records) \
            if isinstance(evidence_records, list) else False
        verdict = canonicalize_verdict(agreed, evidence_ok=evidence_ok)

        if agreed.get("rules_version") and agreed["rules_version"] != rules_version:
            # A verdict reached under a different rules version is not a
            # verdict about this case.
            verdict = canonicalize_verdict({}, evidence_ok=False)

        rec = self._load_case(case_id)
        rec["decision"] = verdict["decision"]
        rec["outcome"] = verdict["outcome"]
        rec["scores"] = {
            "score": verdict["score"],
            "fit_score": verdict["fit_score"],
            "risk": verdict["risk"],
        }
        rec["reasoning"] = verdict["reasoning"]
        rec["weak_spots"] = verdict["weak_spots"]
        rec["corrections"] = verdict["corrections"]
        rec["improvements"] = verdict["improvements"]
        rec["uncertainty"] = verdict["uncertainty"]
        rec["evidence_report"] = evidence_records if isinstance(evidence_records, list) else []
        rec["state"] = STATE_DECIDED
        rec["decided_at"] = now_ts
        rec["eval_rounds"] = int(rec.get("eval_rounds", 0)) + 1
        self._save_case(case_id, rec)

        CaseDecided(case_id, verdict["decision"], verdict["outcome"]).emit()
        return verdict["decision"]

