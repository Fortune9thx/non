        rec["derived_state"] = case_state(rec, _now_ts(), int(self.appeal_window))
        rec["appeal_deadline"] = appeal_deadline(
            rec["decided_at"], int(self.appeal_window)
        ) if rec["decided_at"] else 0
        return json.dumps(rec)

