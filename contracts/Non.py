# ---------------------------------------------------------------------------
# Deterministic transaction-time clock.
#
# datetime.now() is deterministic inside a GenLayer transaction (confirmed
# against genvm-linter's own safety exclusion list, which forbids
# time.time()/uuid.uuid4() but not datetime.now()). gl.vm.get_timestamp()
# is deliberately NOT used: it returns None under gltest direct-mode, which
# would make every window comparison untestable locally.
# ---------------------------------------------------------------------------


def _now_ts() -> int:
    return int(datetime.now(timezone.utc).timestamp())


def _sender() -> str:
    return str(gl.message.sender_address)


def _floor_config(raw, default: int) -> int:
    """Configurable minimums are floored at the protocol default: an
    operator may make Non stricter, never cheaper to lie to."""
    if raw is None or raw == "":
        return default
    try:
        value = int(str(raw))
    except (TypeError, ValueError):
        return default
    if value < default:
        return default
    return value


